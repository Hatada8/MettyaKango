-- ---------------------------------------------------------
-- 0. 共通：updated_at を自動で更新する仕組み
-- ---------------------------------------------------------
create or replace function v2_set_updated_at() returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;


