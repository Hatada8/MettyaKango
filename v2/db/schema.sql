-- ---------------------------------------------------------
-- 5. updated_at の自動更新・アクセス権（v2 のテーブルだけが対象）
--    行の物理削除はしない設計なので、DELETE はできないようにします。
--    RLS（行ごとのアクセス制限）は有効にして、今は「読む・追加・更新」を全員に許可。
--    本番前にここのルールを絞れば、画面のコードを変えずに守りを固められます。
-- ---------------------------------------------------------
do $$
declare
  t   text;
  seq text;
begin
  foreach t in array array[
    'sex_master','symptom_type_master','condition_level_master','memo_type_master',
    'role_master','permission_master','department_master','symptom_master',
    'employee_master','patient_master','family_master',
    'admission','patient_symptom','patient_memo','patient_ai_summary',
    'employee_favorite','family_chat','vital_sign'
  ] loop
    -- updated_at の自動更新
    execute format('create or replace trigger %I before update on %I for each row execute function v2_set_updated_at()', t || '_updated_at', t);

    -- 権限：読む・追加・更新だけ（削除は不可）
    execute format('grant select, insert, update on %I to anon, authenticated', t);
    execute format('revoke delete, truncate on %I from anon, authenticated', t);
    for seq in
      select pg_get_serial_sequence(t, a.attname)
      from pg_attribute a
      where a.attrelid = t::regclass and a.attidentity <> ''
    loop
      execute format('grant usage, select on sequence %s to anon, authenticated', seq);
    end loop;

    -- RLS
    execute format('alter table %I enable row level security', t);
    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = t and policyname = 'v2_select') then
      execute format('create policy v2_select on %I for select to anon, authenticated using (true)', t);
    end if;
    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = t and policyname = 'v2_insert') then
      execute format('create policy v2_insert on %I for insert to anon, authenticated with check (true)', t);
    end if;
    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = t and policyname = 'v2_update') then
      execute format('create policy v2_update on %I for update to anon, authenticated using (true) with check (true)', t);
    end if;
  end loop;
end $$;


